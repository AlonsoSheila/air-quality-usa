# TAB 4 — EVENTS
# ═══════════════════════════════════════════════════════════════════════════════
with tabs[3]:
    st.header("Documented Air Quality Events")
    st.caption("Events mark months with the highest count of days above AQI 150, plus any separately documented extreme episodes (e.g. a single record-breaking day). A city may appear more than once.")

    events_sel = events[
        events["city"].isin(selected_cities) &
        (events["event_year"] >= year_range[0]) &
        (events["event_year"] <= year_range[1])
    ].copy()

    def circ_mean(deg):
        r = np.deg2rad(deg.dropna())
        return (np.degrees(np.arctan2(np.sin(r).mean(),np.cos(r).mean()))+360)%360

    if events_sel.empty:
        st.info(f"No documented events within {year_range[0]}–{year_range[1]} for the selected cities.")
    else:
        for _, ev in events_sel.iterrows():
            city   = ev["city"]
            year   = int(ev["event_year"])
            month  = int(ev["event_month"])
            label  = ev["event_label"]
            mname  = ["Jan","Feb","Mar","Apr","May","Jun",
                      "Jul","Aug","Sep","Oct","Nov","Dec"][month-1]

            month_aqi = aqi[(aqi["city"]==city) &
                            (aqi["date"].dt.year==year) &
                            (aqi["date"].dt.month==month)]
            n_over  = int((month_aqi["aqi_composite"] > 150).sum())
            max_aqi = month_aqi["aqi_composite"].max() if len(month_aqi) else None

            ev_key_ny  = (city=="New York" and year==2023 and month==6)
            ev_key_chi = (city=="Chicago"  and year==2023 and month==6)
            wind_scope = "month"
            if ev_key_ny:
                wind_scope = "documented event days (6–8 June)"
                wind_sub = meteo[(meteo["city"]==city) &
                                 (meteo["date"]>="2023-06-06") &
                                 (meteo["date"]<="2023-06-08")]
            elif ev_key_chi:
                wind_scope = "documented event days (27–28 June)"
                wind_sub = meteo[(meteo["city"]==city) &
                                 (meteo["date"]>="2023-06-27") &
                                 (meteo["date"]<="2023-06-28")]
            else:
                wind_sub = meteo[(meteo["city"]==city) &
                                 (meteo["date"].dt.year==year) &
                                 (meteo["date"].dt.month==month)]

            wind_speed = wind_sub[wind_sub["parameter"]=="Wind Speed - Resultant"]["value"]
            wind_dir   = wind_sub[wind_sub["parameter"]=="Wind Direction - Resultant"]["value"]

            with st.expander(f"**{CITY_DISPLAY.get(city, city)}** — {label} ({mname} {year})"):
                c1, c2, c3, c4 = st.columns(4)
                c1.metric("Days AQI > 150", n_over)
                c2.metric("Max AQI that month", f"{max_aqi:.0f}" if max_aqi else "—")
                if len(wind_speed):
                    c3.metric("Mean wind speed", f"{wind_speed.mean():.1f} kt")
                if len(wind_dir):
                    c4.metric("Wind direction", f"{circ_mean(wind_dir):.0f}°")
                st.caption(f"Defining parameter: {ev['defining_parameter']} · Wind: mean over the {wind_scope}")

    st.divider()
    st.header("Worst AQI Days per City")
    st.caption(f"Top 5 worst days per city, sorted by AQI descending · {year_range[0]}–{year_range[1]}")

    top_days = []
    for city in cities_ordered:
        top_days.append(
            aqi_f[aqi_f["city"]==city]
            .sort_values("aqi_composite",ascending=False).head(5))
    if top_days:
        top_all = pd.concat(top_days).sort_values("aqi_composite",ascending=False)
        top_all = top_all[["city","date","aqi_composite","aqi_category","aqi_defining_parameter"]].copy()
        top_all["date"] = top_all["date"].dt.strftime("%Y-%m-%d")
        top_all["city"] = top_all["city"].map(lambda x: CITY_DISPLAY.get(x, x))
